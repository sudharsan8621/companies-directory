// Additional utility functions for data manipulation

export const getUniqueIndustries = () => {
  return [...new Set(mockCompanies.map(company => company.industry))].sort();
};

export const getUniqueLocations = () => {
  return [...new Set(mockCompanies.map(company => company.location))].sort();
};

export const getCompanyById = (id) => {
  return mockCompanies.find(company => company.id === parseInt(id));
};

export const filterCompaniesByIndustry = (industry) => {
  return mockCompanies.filter(company => company.industry === industry);
};

export const filterCompaniesByLocation = (location) => {
  return mockCompanies.filter(company => 
    company.location.toLowerCase().includes(location.toLowerCase())
  );
};

export const searchCompanies = (searchTerm) => {
  const term = searchTerm.toLowerCase();
  return mockCompanies.filter(company =>
    company.name.toLowerCase().includes(term) ||
    company.description.toLowerCase().includes(term) ||
    company.industry.toLowerCase().includes(term) ||
    company.location.toLowerCase().includes(term)
  );
};

export const getCompanyStats = () => {
  const stats = {
    totalCompanies: mockCompanies.length,
    totalEmployees: mockCompanies.reduce((sum, company) => sum + company.employees, 0),
    averageEmployees: Math.round(mockCompanies.reduce((sum, company) => sum + company.employees, 0) / mockCompanies.length),
    industries: getUniqueIndustries().length,
    oldestCompany: mockCompanies.reduce((oldest, company) => 
      company.founded < oldest.founded ? company : oldest
    ),
    newestCompany: mockCompanies.reduce((newest, company) => 
      company.founded > newest.founded ? company : newest
    ),
    largestCompany: mockCompanies.reduce((largest, company) => 
      company.employees > largest.employees ? company : largest
    ),
    smallestCompany: mockCompanies.reduce((smallest, company) => 
      company.employees < smallest.employees ? company : smallest
    )
  };
  return stats;
};

// Industry distribution
export const getIndustryDistribution = () => {
  const distribution = {};
  mockCompanies.forEach(company => {
    if (distribution[company.industry]) {
      distribution[company.industry]++;
    } else {
      distribution[company.industry] = 1;
    }
  });
  return distribution;
};

// Get companies by size
export const getCompaniesBySize = () => {
  return {
    small: mockCompanies.filter(c => c.employees < 200),  // < 200 employees
    medium: mockCompanies.filter(c => c.employees >= 200 && c.employees < 500),  // 200-499
    large: mockCompanies.filter(c => c.employees >= 500 && c.employees < 1000),  // 500-999
    enterprise: mockCompanies.filter(c => c.employees >= 1000)  // 1000+
  };
};

// Get companies by founding decade
export const getCompaniesByDecade = () => {
  const decades = {};
  mockCompanies.forEach(company => {
    const decade = Math.floor(company.founded / 10) * 10;
    const decadeKey = `${decade}s`;
    if (decades[decadeKey]) {
      decades[decadeKey].push(company);
    } else {
      decades[decadeKey] = [company];
    }
  });
  return decades;
};

